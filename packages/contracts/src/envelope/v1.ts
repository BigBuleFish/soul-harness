/**
 * Stimulus envelopes — two layers, one authority boundary.
 *
 *   adapter ──StimulusInputV1──▶ Ingress ──StimulusV1──▶ Runtime
 *
 * Design split (SH-004 decision B1, refined):
 *   - The **envelope** owns stable, core fields: event identity, delivery
 *     identity, persona scope, source attribution and source-claimed time.
 *   - The **payload** is an open, versioned extension area owned by adapter /
 *     plugin protocols. The core fixes its *shape* (a JSON object with a
 *     namespaced `kind` and a `version`) and never enumerates platform event
 *     types.
 *
 * Time authority:
 *   - `occurredAt` MAY be supplied by the source. It is a *claim* about when the
 *     stimulus happened, never a system-authoritative timestamp, and may be
 *     absent, skewed or wrong.
 *   - `receivedAt` MUST NOT be supplied by an adapter. It exists only on the
 *     normalized envelope and is generated by Ingress inside the trusted
 *     receive path. An adapter that submits it is rejected by the closed
 *     top-level schema, not silently ignored.
 */

import type { AdapterEventRef, AdapterId, PersonaId, RequestNonce, SourceId } from '../ids/types.js';
import type { JsonObject } from '../json.js';
import type { StimulusInputVersion, StimulusVersion } from '../version.js';

/**
 * Open extension payload.
 *
 * `kind` is a namespaced, lower-case type name (`qq.message`, `mc.world`, …)
 * whose vocabulary is defined by the adapter protocol, not here.
 * `version` lets an adapter evolve its own payload without a core version bump.
 * Additional properties are explicitly allowed: this is the designated
 * extension area, and it is the only place where unknown keys are tolerated.
 */
export type StimulusPayload = JsonObject & {
  readonly kind: string;
  readonly version: number;
};

/**
 * Adapter-submitted stimulus.
 *
 * This is the ONLY envelope an external caller may construct. It has no
 * `receivedAt`: receipt time is assigned by the Harness.
 */
export interface StimulusInputV1 {
  /** Always `soul.stimulus.input.v1`; drives version negotiation. */
  readonly schema: StimulusInputVersion;
  /** Target persona. Explicit, never inferred from "most recent session". */
  readonly personaId: PersonaId;
  /** Registered adapter that produced the stimulus. `system.*` for internal. */
  readonly adapterId: AdapterId;
  /** Registered source name, authorized for that adapter. */
  readonly source: SourceId;
  /** Adapter-side stimulus reference; retries of one stimulus MUST reuse it. */
  readonly adapterEventRef: AdapterEventRef;
  /** Per-delivery nonce; internal retries of one delivery MUST reuse it. */
  readonly requestNonce: RequestNonce;
  /**
   * Source-claimed time of the stimulus, Unix milliseconds.
   * NOT authoritative: the Harness never uses it as "when we learned this".
   */
  readonly occurredAt?: number;
  /** Open, versioned extension area. */
  readonly payload: StimulusPayload;
}

/**
 * Normalized stimulus produced by Ingress.
 *
 * Identical to the input except that the version is re-stamped and `receivedAt`
 * is added by trusted code. Runtime consumes only this type, so no downstream
 * module ever has to ask "did the adapter lie about when this arrived?".
 */
export type StimulusV1 = Omit<StimulusInputV1, 'schema'> & {
  /** Always `soul.stimulus.v1`. */
  readonly schema: StimulusVersion;
  /** Unix milliseconds at which Ingress accepted the envelope. Ingress-owned. */
  readonly receivedAt: number;
};
